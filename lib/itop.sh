itop_init ()
{
    local count=0
    while [ $count -lt 300 ] ; do
        CPU_HIST+=(0)
        ((count++)) 
    done
    local count=0
    while [ $count -lt 300 ] ; do
        MEM_HIST+=(0)
        ((count++)) 
    done

    read -r key val _ < /proc/meminfo
    total_mem=$val  

    while IFS=':' read -r key val ; do
        if [[ $key == "vendor_id"* ]] ; then
            if [[ $val == " GenuineIntel" ]] ; then
                vendor="Intel"
                break
            elif [[ $val == " AuthenticAMD" ]] ; then
                vendor="AMD"
                break
            else
                vendor="unknown"
                break
            fi
            break
        fi
    done < /proc/cpuinfo

    # whiile IFS=':' read -r key val ; do
    #     if [[ $key == ]]
    # done < /proc/cpuinfo

    read -r base_freq < /sys/devices/system/cpu/cpu0/cpufreq/base_frequency
}

itop_main()
{
    local ROW=$1
    local COL=$2
    local WIDTH=$3
    local HEIGHT=$4
#    local prev_total=$5
#    local prev_idle=$6

    # while IFS=':' read -r key value < /proc/cpuinfo; do
    #     if [[ "$key" == "model name" ]]; then
    #         model_name=${value# }
    #         break
    #     fi
    # done

    read -r label user nice system idle iowait irq softirq steal _ < /proc/stat
    read -r freq_khz < /sys/devices/system/cpu/cpu0/cpufreq/scaling_cur_freq
    total_idle=$((idle+iowait))
    total_time=$((user+nice+system+total_idle+irq+softirq+steal))

    diff_total=$((total_time-prev_total))
    diff_idle=$((total_idle-prev_idle))

    if [ "$diff_total" -gt 0 ] ; then
        cpu_prctg=$(( ((diff_total-diff_idle) * 100)/diff_total ))
    fi

    prev_total=$total_time
    prev_idle=$total_idle

    # #=====================================================
# !!! CODE GENERATED BY GEMINI. !!!
    CPU_HIST+=("$cpu_prctg")
    CPU_HIST=("${CPU_HIST[@]:1}")
    # if [ "${#CPU_HIST[@]}" -gt 300 ]; then
    #     CPU_HIST=("${CPU_HIST[@]:1}")
    # fi

    # while IFS=':' read -r key val; do
    #     if [[ "$key" == "cpu MHz" ]] ; then
    #         freq_khz=${val# }
    #         break
    #     fi
    # done < /proc/cpuinfo

    freq_ghz_int=$((freq_khz/1000000))
    freq_ghz_dec=$(((freq_khz/10000)%100))

    base_freq_ghz_int=$((base_freq/1000000))
    base_freq_ghz_dec=$(((base_freq/10000)%100))

    while read -r key val _ ; do 
        if [[ $key == "MemAvailable:" ]] ; then
            mem_free=$val
            break
        fi
    done < /proc/meminfo

    mem_prctg=$(( ((total_mem-mem_free) * 100) / total_mem))

    MEM_HIST+=("$mem_prctg")
    MEM_HIST=("${MEM_HIST[@]:1}")

    total_mem_gB=$((total_mem/1000000))

    ui_draw_box "$ROW" "$COL" "$WIDTH" "$((HEIGHT/2))" 2 "$C_TEAL"
    ui_draw_text "CPU: ${model_name}" "$ROW" "$((COL+1))" ""
    ui_draw_text "${cpu_prctg}" "$((ROW+1))" "$((COL + WIDTH - 5))" "$C_RED"
    ui_draw_CPU_sparkline "$((ROW+1))" "$((COL+1))" "$((WIDTH-7))" ""
    ui_draw_text "%" "$((ROW+1))" "$((COL+WIDTH-2))" "$C_RED"
    ui_draw_text "  GHz" "$ROW" "$((COL+WIDTH-7))" "$C_RED"
    ui_draw_text "$freq_ghz_int" "$ROW" "$((COL+WIDTH-10))" "$C_RED"
    ui_draw_text ".$freq_ghz_dec" "$ROW" "$((COL+WIDTH-9))" "$C_RED"
    ui_draw_text "CPU info:" "$((ROW+3))" "$((COL+1))" "$C_BLUE"

    ui_draw_text "Vendor: " "$((ROW+5))" "$((COL+1))" ""
    if [[ $vendor == "AMD" ]] ; then
        ui_draw_text "${vendor}" "$((ROW+5))" "$((COL+9))" "$C_RED"
    elif [[ $vendor == "Intel" ]] ; then
        ui_draw_text "${vendor}" "$((ROW+5))" "$((COL+9))" "$C_BLUE"
    else
        ui_draw_text "${vendor}" "$((ROW+5))" "$((COL+9))" "$C_YELLOW"
    fi

    ui_draw_text "Base Clock: ${base_freq_ghz_int}.${base_freq_ghz_dec} GHz" "$((ROW+7))" "$((COL+1))"

    ui_draw_box "$((ROW+(HEIGHT/2)))" "$COL" "$WIDTH" "$((HEIGHT/2))" 2 "$C_ORANGE"
    ui_draw_text "RAM" "$((ROW+(HEIGHT/2)))" "$((COL+1))" ""
    ui_draw_RAM_sparkline "$((ROW+(HEIGHT/2)+1))" "$((COL+1))" "$((WIDTH-7))" ""
    ui_draw_text "$mem_prctg" "$((ROW+(HEIGHT/2)+1))" "$((COL + WIDTH - 5))" "$C_RED"
    ui_draw_text "%" "$((ROW+(HEIGHT/2)+1))" "$((COL+WIDTH-2))" "$C_RED"
    ui_draw_text "RAM info:" "$((ROW+(HEIGHT/2)+3))" "$((COL+1))" "$C_BLUE"
    ui_draw_text "Total Memory Installed: $total_mem_gB GB ($total_mem kB)" "$((ROW+(HEIGHT/2)+5))" "$((COL+1))" ""
#    ui_draw_text "$val" "$((ROW+2))" "$((COL+WIDTH-2))" "$C_RED"
    # printf -v string "\033[%d;%dH%d" "$ROW" "$COL" "$cpu_prctg"
    # FRAME+=$string
}